package com.example.go4burn.utils;

public class UnitConverter {
    public double cmToM(double cm) {
        return cm*100;
    }
    public double mToCm(double m) {
        return m/100;
    }
    public double kgToLb(double kg) {
        return kg*2.20462;
    }
    public double lbToKg(double lb) {
        return lb/2.20462;
    }
}
